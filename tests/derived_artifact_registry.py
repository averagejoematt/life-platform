"""tests/derived_artifact_registry.py — the derived-artifact registry (epic #2986).

WHY THIS EXISTS
---------------
A derived artifact needs four things: a **generator**, a **writer** that can self-heal it,
a **guard**, and that guard placed in a **lane the artifact's inputs trigger**. Discovery
below finds **28 scripts** writing a git-tracked artifact and, until this file, nothing
declared which of the four each one has. So the gaps were found one incident at a time, and each one cost
a misattributed main-red or weeks of silent drift:

  * `incident_log_patterns` (#2975) — guard ✓, but in a lane a `docs/**` change cannot
    trigger. Every wrap adds incident rows by design, so the red landed on whichever later
    commit happened to touch `tests/**`, and whoever debugged it started from an unrelated
    diff. Structural, not bad luck.
  * `generate_platform_model` — guard ✓ and in the right workflow, but OUTSIDE the
    `premerge` marker, so a `lambdas/**` PR that stales the model reds `main` rather than
    the PR that did it.
  * `generate_mcp_tool_catalog` — has a `--check` wired into NOTHING: no workflow step, no
    pytest, no `run_generators()`. Measured 2026-08-22: stale, and stale **behind a fresh
    timestamp** — the reconcile bot touches the file daily because `sync_doc_metadata`
    rewrites its `Total tools:` literal, while the generated body had not been re-run since
    2026-07-25. The doc contradicted itself two lines apart: `Total tools: 76` above
    `## All 72 Tools`.

Three artifacts, three genuinely different broken triples. That is a class, and a class
gets a registry (`docs/CHARTER.md` primitive 1) with a derivation guard over it (primitive
2), not three more one-off fixes.

HOW IT'S GUARDED (guard the SET, not the instance)
--------------------------------------------------
`discover_generators()` reads the tree for every script that writes a path under a
committed artifact root. `ARTIFACTS` records one decision per discovered generator.
`tests/test_derived_artifact_registry_2986.py` asserts BOTH directions:

  * every discovered generator has an entry → a NEW generator writing a committed artifact
    fails the build until someone classifies it as DERIVED, BUILDER or EXCLUDED;
  * every entry still resolves to a real discovered generator → the registry cannot rot
    into a hand-list describing scripts that no longer exist.

and, for every `DERIVED` entry, that its declared guard command really appears in its
declared lane, and that **the lane's trigger paths cover the artifact's inputs** — the
#2975 rule, generalized. That last assertion is the one the three incidents above all
failed, each in a different place.

WHY A DECLARED LANE AND NOT "THERE IS A TEST"
---------------------------------------------
"Is there a guard?" was already answerable and already answered YES for two of the three.
The question that separated a working guard from a misattributing one was *which lane*, and
that is not derivable from the guard alone — it is a fact about the workflow's path filter.
So the lane is declared and then CHECKED against the workflow file, rather than inferred.
"""

