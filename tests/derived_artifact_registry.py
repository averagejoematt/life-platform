# ── Decisions ─────────────────────────────────────────────────────────────────
#
# The distinction that matters is NOT "generated vs hand-written" — nearly everything here
# is generated. It is **who is responsible for noticing staleness**. A DERIVED artifact's
# answer is "CI, on the commit that staled it"; a BUILDER's is "the person who runs the
# build step", and that is a legitimate answer as long as the step is named.
DERIVED = "DERIVED"  # continuously derived from repo state — needs writer + guard + lane
BUILDER = "BUILDER"  # regenerated by a named build/deploy step; no drift contract
EXCLUDED = "EXCLUDED"  # discovery names the path but this script does not own it
VALID_DECISIONS = frozenset({DERIVED, BUILDER, EXCLUDED})


def _derived(generator, outputs, writer, guard, guard_lane, inputs, reconciled, reason):
    return {
        "decision": DERIVED,
        "generator": generator,
        "outputs": tuple(outputs),
        "writer": writer,
        "guard": guard,
        "guard_lane": guard_lane,
        # The paths whose change can stale this artifact. The lane must trigger on them,
        # or the guard reds somebody else's commit.
        "inputs": tuple(inputs),
        "reconciled": reconciled,  # in ci-cd.yml's run_generators()
        "reason": reason,
    }


def _builder(generator, step, reason):
    """A builder must name the STEP that runs it. 'someone runs it' is how an artifact
    goes a month stale behind a fresh timestamp — the #2986 catalog finding."""
    return {"decision": BUILDER, "generator": generator, "step": step, "reason": reason}


def _excluded(generator, reason):
    return {"decision": EXCLUDED, "generator": generator, "reason": reason}


