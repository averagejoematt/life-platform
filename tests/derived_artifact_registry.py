# ── Discovery ─────────────────────────────────────────────────────────────────
#
# Two filters, and BOTH are load-bearing. Dropping either produced a useless scan when
# this was first written: a permissive version found 59 "generators", most of them
# `check_*.py` scripts that only READ a site/ path, and report writers dumping transient
# `docs/restart/_*.txt` files that are not committed at all.
#
#   1. the path must be the TARGET of a write call, resolved through module-level
#      constants — not merely a string the module mentions;
#   2. the path must be GIT-TRACKED — "committed artifact" is a literal claim, and the
#      index is the only honest way to check it.


def _flatten_div(node: ast.AST) -> list[str] | None:
    """`ROOT / "docs" / "X.md"` → ['docs', 'X.md']; anything else → None."""
    parts: list[str] = []
    cur = node
    while isinstance(cur, ast.BinOp) and isinstance(cur.op, ast.Div):
        if not (isinstance(cur.right, ast.Constant) and isinstance(cur.right.value, str)):
            return None
        parts.append(cur.right.value)
        cur = cur.left
    if not parts:
        return None
    parts.reverse()
    return parts


def _resolve_path_expr(node: ast.AST, consts: dict[str, str]) -> str | None:
    """A relative artifact path for a path expression, or None."""
    if isinstance(node, ast.Name):
        return consts.get(node.id)
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value if "/" in node.value else None
    parts = _flatten_div(node)
    if parts:
        # A `/`-chain rooted at a Name we know resolves through it; one rooted at
        # ROOT/REPO_ROOT starts at its first literal segment.
        base = node
        while isinstance(base, ast.BinOp):
            base = base.left
        if isinstance(base, ast.Name) and base.id in consts:
            return "/".join([consts[base.id]] + parts)
        return "/".join(parts)
    return None


def _module_constants(tree: ast.AST) -> dict[str, str]:
    """Module-level `NAME = <path expr>` bindings, as relative paths."""
    consts: dict[str, str] = {}
    for node in getattr(tree, "body", []):
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        parts = _flatten_div(node.value)
        if parts:
            consts[target.id] = "/".join(parts)
        elif isinstance(node.value, ast.Constant) and isinstance(node.value.value, str) and "/" in node.value.value:
            consts[target.id] = node.value.value
    return consts


def _has_write_call(tree: ast.AST) -> bool:
    """Does this module perform a file write at all? AST-only — a substring check for
    `open(` matches every READ, which is how a first draft of this scan turned 9 real
    generators into 59 candidates, most of them `check_*.py` scripts."""
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        fn = node.func
        if isinstance(fn, ast.Attribute) and fn.attr in ("write_text", "write_bytes", "writelines"):
            return True
        if isinstance(fn, ast.Attribute) and fn.attr == "dump" and isinstance(fn.value, ast.Name) and fn.value.id == "json":
            return True
        if isinstance(fn, ast.Name) and fn.id == "open":
            mode = node.args[1] if len(node.args) > 1 else None
            mode_val = mode.value if isinstance(mode, ast.Constant) else None
            for kw in node.keywords:
                if kw.arg == "mode" and isinstance(kw.value, ast.Constant):
                    mode_val = kw.value.value
            if isinstance(mode_val, str) and ("w" in mode_val or "a" in mode_val or "x" in mode_val):
                return True
    return False


def _named_paths(tree: ast.AST) -> set[str]:
    """Every artifact-root-relative path this module names, however it names it.

    Deliberately WIDER than "the resolved target of a write call". The precise version
    missed `deploy/sync_doc_metadata.py` — the largest generator in the repo — because it
    writes through a loop over computed paths, and it missed the whole `v4_build_*` family
    for the same reason. Under-discovery is the failure mode this registry exists to
    prevent (an unclassified generator is invisible forever); over-discovery costs one
    BUILDER/EXCLUDED line with a reason. So the write-call check gates WHETHER a module is a
    candidate, and this supplies WHICH artifacts to attribute to it.
    """
    consts = _module_constants(tree)
    out: set[str] = set(consts.values())
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            if "/" in node.value and not node.value.startswith(("http", "//")):
                out.add(node.value)
        else:
            parts = _flatten_div(node)
            if parts:
                out.add("/".join(parts))
    return {p for p in out if p.split("/")[0] in ARTIFACT_ROOTS}


def _tracked_paths(repo: str = REPO) -> frozenset[str]:
    """Every git-tracked path under the artifact roots. Cached per process."""
    global _TRACKED_CACHE
    if _TRACKED_CACHE is None:
        import subprocess

        out = subprocess.run(
            ["git", "-C", repo, "ls-files", "--", *ARTIFACT_ROOTS],
            capture_output=True,
            text=True,
            timeout=60,
        )
        _TRACKED_CACHE = frozenset(ln.strip() for ln in out.stdout.splitlines() if ln.strip())
    return _TRACKED_CACHE


_TRACKED_CACHE: frozenset[str] | None = None


def discover_generators(repo: str = REPO) -> dict[str, tuple[str, ...]]:
    """`{rel_script_path: (artifact_path, …)}` for every script that writes committed output.

    NOT hand-listed — the point is that a new generator must be classified rather than
    silently added. `deploy/` is scanned alongside `scripts/` because sync_doc_metadata,
    the biggest generator in the repo, lives there.
    """
    tracked = _tracked_paths(repo)
    out: dict[str, tuple[str, ...]] = {}
    for top in GENERATOR_DIRS:
        d = os.path.join(repo, top)
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            if not name.endswith(".py"):
                continue
            rel = f"{top}/{name}"
            try:
                with open(os.path.join(d, name), encoding="utf-8") as fh:
                    tree = ast.parse(fh.read())
            except (OSError, SyntaxError):
                continue
            if not _has_write_call(tree):
                continue
            committed = sorted(p for p in _named_paths(tree) if p in tracked)
            if committed:
                out[rel] = tuple(committed)
    return out


# ── Lane resolution ───────────────────────────────────────────────────────────
def lane_trigger_paths(lane: str, repo: str = REPO) -> list[str]:
    """The union of a lane workflow's push + pull_request path globs."""
    import yaml

    path = os.path.join(repo, _LANE_WORKFLOW[lane])
    with open(path, encoding="utf-8") as fh:
        spec = yaml.safe_load(fh)
    # PyYAML resolves the bare key `on:` to the boolean True (YAML 1.1 truthiness).
    triggers = spec.get("on", spec.get(True)) or {}
    globs: list[str] = []
    for event in ("push", "pull_request"):
        globs += (triggers.get(event) or {}).get("paths") or []
    return globs


def lane_covers(input_glob: str, trigger_globs: list[str]) -> bool:
    """Does some trigger glob fire on a change matching `input_glob`?

    Compared glob-to-glob, not path-to-glob: the registry declares an input as a pattern
    ('lambdas/**'), and the question is whether the lane's filter admits that pattern.
    A trigger of `lambdas/**` covers an input of `lambdas/**` and of `lambdas/web/x.py`;
    an input of `lambdas/**` is NOT covered by a trigger of `lambdas/web/x.py`.
    """
    probe = input_glob.replace("/**", "/_probe_/x.py").replace("*", "x")
    for g in trigger_globs:
        if g == input_glob:
            return True
        pattern = g.replace("/**", "/*")
        if fnmatch.fnmatch(probe, pattern) or fnmatch.fnmatch(probe, g.replace("**", "*")):
            return True
    return False


def reconcile_whitelist_re(repo: str = REPO) -> "re.Pattern[str]":
    """The compiled generator-output whitelist from ci-cd.yml's reconcile step.

    #3012's live lesson: adding a generator to run_generators() without adding its
    output to ALLOWED makes the reconcile job refuse-and-red on the NEXT innocent
    merge — the lane had the writer but not the write.
    """
    with open(os.path.join(repo, ".github", "workflows", "ci-cd.yml"), encoding="utf-8") as fh:
        text = fh.read()
    m = re.search(r"ALLOWED='([^']+)'", text)
    if not m:
        raise AssertionError("ci-cd.yml no longer defines the reconcile ALLOWED whitelist")
    return re.compile(m.group(1))


def run_generators_commands(repo: str = REPO) -> list[str]:
    """The command lines inside ci-cd.yml's `run_generators()` shell function."""
    with open(os.path.join(repo, ".github", "workflows", "ci-cd.yml"), encoding="utf-8") as fh:
        text = fh.read()
    start = text.index("run_generators() {")
    end = text.index("\n          }", start)
    return [ln.strip() for ln in text[start:end].splitlines() if "python3" in ln]
