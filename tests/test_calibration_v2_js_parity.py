"""tests/test_calibration_v2_js_parity.py — the browser port of calibration-v2 is the Python method, exactly.

Owner ruling 2026-11-09: calibration-v2 is adopted everywhere. /method/grade-your-coach/ grades a pasted ledger in the
reader's browser, so it needs the method in JavaScript (``site/assets/js/calibration-v2-core.js``). Two copies of one
method are held to ONE fixture, ``tests/fixtures/calibration_v2_vectors.json``:

  * this module: the fixture is exactly what ``experiment.calibration_v2.assess(pairs)`` returns today (no baseline —
    a pasted ledger has none), so a change to the Python method reds here until the fixture is regenerated;
  * ``tests/js/calibration_v2_core.test.mjs`` (``node --test``): the JS port reproduces every vector with deep
    equality — no tolerance (ADR-105: every served number is already rounded at the source).

Regenerate after an intended change to the method's words or outputs (never its constants):

    python3 -c "import sys; sys.path.insert(0, 'tests'); import test_calibration_v2_js_parity as t; print(t.dump(), end='')" \
        > tests/fixtures/calibration_v2_vectors.json

MUTATION CONTROL: ``test_the_fixture_would_catch_a_changed_answer`` perturbs one vector and proves the comparison
fails, so the equality is not vacuous. Every ledger here is SYNTHETIC.
"""

from __future__ import annotations

import copy
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lambdas"))

from experiment import calibration_v2  # noqa: E402

VECTORS = ROOT / "tests" / "fixtures" / "calibration_v2_vectors.json"


def _ledger(spec, seed):
    """[(stated, hits, n), …] → shuffled (stated, outcome) pairs, deterministic."""
    pairs = []
    for stated, hits, n in spec:
        pairs += [(stated, 1)] * hits + [(stated, 0)] * (n - hits)
    random.Random(seed).shuffle(pairs)
    return pairs


def _random_ledger(seed, n):
    rng = random.Random(seed)
    out = []
    for _ in range(n):
        p = round(rng.choice([0.05, 0.2, 0.35, 0.5, 0.55, 0.62, 0.7, 0.8, 0.85, 0.9, 0.97, 1.0]), 2)
        out.append((p, 1 if rng.random() < p * 0.9 else 0))
    return out


CASES = {
    "empty": [],
    "one_call": [(0.7, 1)],
    "nutrition_shaped_over_at_50": _ledger([(0.5, 12, 43), (0.7, 1, 1)], 1),
    "consistent_one_level": _ledger([(0.5, 22, 46)], 2),
    "insufficient_two_calls": _ledger([(0.5, 1, 2)], 3),
    "under_at_80": _ledger([(0.8, 326, 370)], 4),
    "mixed_over_and_under": _ledger([(0.3, 26, 40), (0.9, 18, 40)], 5),
    "over_at_two_levels": _ledger([(0.6, 5, 40), (0.9, 12, 40)], 6),
    "estimable_tracks": _ledger([(0.2, 5, 30), (0.5, 15, 30), (0.8, 24, 30)], 7),
    "estimable_flat": _ledger([(0.2, 14, 30), (0.5, 15, 30), (0.8, 16, 30)], 8),
    "random_60": _random_ledger(9, 60),
    "random_250": _random_ledger(10, 250),
    "edges_zero_and_one": _ledger([(0.0, 0, 10), (1.0, 10, 10), (0.5, 4, 9)], 11),
}


def build() -> dict:
    return {
        "_note": "Generated by tests/test_calibration_v2_js_parity.py --write from experiment.calibration_v2.assess. Do not hand-edit.",
        "method_version": calibration_v2.METHOD_VERSION,
        "constants": calibration_v2.constants(),
        "vectors": [{"name": k, "pairs": [list(p) for p in v], "expected": calibration_v2.assess(v)} for k, v in CASES.items()],
    }


def _norm(x):
    return json.loads(json.dumps(x))


def test_the_fixture_is_the_python_method_today():
    committed = json.loads(VECTORS.read_text(encoding="utf-8"))
    assert committed == _norm(build()), "calibration-v2 changed: regenerate with the command in this module's docstring"


def test_the_vectors_cover_every_answer():
    built = build()["vectors"]
    seen = {(q, v["expected"][q]["result"]) for v in built for q in ("estimability", "confidence_direction")}
    for want in (
        ("estimability", "estimable"),
        ("estimability", "not_estimable"),
        ("confidence_direction", "over_confident"),
        ("confidence_direction", "under_confident"),
        ("confidence_direction", "mixed"),
        ("confidence_direction", "insufficient_evidence"),
        ("confidence_direction", "consistent_not_established"),
        ("confidence_direction", "no_resolved_calls"),
    ):
        assert want in seen, want


def test_the_fixture_would_catch_a_changed_answer():
    committed = json.loads(VECTORS.read_text(encoding="utf-8"))
    mutated = copy.deepcopy(committed)
    mutated["vectors"][2]["expected"]["confidence_direction"]["wording"] += " (tampered)"
    assert mutated != _norm(build())


def dump() -> str:
    """The fixture's text. The test never writes it; regenerate with the command in the module docstring."""
    return json.dumps(_norm(build()), indent=1, ensure_ascii=False) + "\n"


def test_the_fixture_text_is_byte_stable():
    assert VECTORS.read_text(encoding="utf-8") == dump()
