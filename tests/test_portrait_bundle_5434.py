"""#5434 — the OG coach-card sweep could not parse the generated portrait bundle.

Cause: the reader cut the PORTRAITS payload at the first ``;`` — which sits inside a string
value (offset 165 of the real bundle, a char-54 string opening) — so json.loads died with
"Unterminated string starting at: line 1 column 55" on every run and no coach card was
written. The fix reads one complete JSON value with raw_decode.

Pillow-free on purpose (web.portrait_bundle is stdlib), so this runs in every CI lane.
"""

import json
import os
import sys
from datetime import datetime, timedelta, timezone

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from operational import qa_check_coach_cards as qcc  # noqa: E402
from web import portrait_bundle as pb  # noqa: E402

NOW = datetime(2026, 10, 27, 12, 0, tzinfo=timezone.utc)


def _bundle(recipes, aliases=None):
    """The structure of scripts/v4_build_portraits.build() output: header comments, then two
    single-line exports with compact JSON. String values carry ';' like the real recipes."""
    return (
        "// GENERATED by scripts/v4_build_portraits.py — DO NOT EDIT\n"
        "// Signed recipes only (ADR-106 §3)\n"
        f"export const PORTRAITS = {json.dumps(recipes, sort_keys=True, separators=(',', ':'))};\n"
        f"export const ALIASES = {json.dumps(aliases or {}, sort_keys=True, separators=(',', ':'))};\n"
    )


SEMI = {"persona_id": "a_coach", "notes": "ink; wash; hatch", "_meta": {"sign_off": {"by": "x", "date": "2026-01-01", "sheet": "s"}}}
FIXTURE = _bundle({"a_coach": SEMI, "b_coach": dict(SEMI, persona_id="b_coach")}, {"b": "b_coach"})


def _naive_first_semicolon_reader(text):
    """The pre-#5434 reader, kept as the mutation control."""
    marker = "export const PORTRAITS = "
    start = text.index(marker) + len(marker)
    return json.loads(text[start : text.index(";", start)])


def test_mutation_control_old_reader_dies_on_the_fixture():
    with pytest.raises(json.JSONDecodeError, match="Unterminated string"):
        _naive_first_semicolon_reader(FIXTURE)


def test_reader_parses_semicolons_in_strings_and_trailing_exports():
    recipes = pb.load_signed_recipes_from_bundle(FIXTURE)
    assert sorted(recipes) == ["a_coach", "b_coach"]
    assert recipes["a_coach"]["notes"] == "ink; wash; hatch"


def test_real_generated_bundle_parses():
    import v4_build_portraits as vbp

    content, _skipped = vbp.build()
    recipes = pb.load_signed_recipes_from_bundle(content)
    assert recipes and all(r.get("persona_id") == pid for pid, r in recipes.items())


@pytest.mark.parametrize(
    "text",
    [
        "export const OTHER = {};\n",
        'export const PORTRAITS = {"a":1;\n',
        "export const PORTRAITS = [1,2];\n",
        "export const PORTRAITS = \n",
    ],
)
def test_malformed_bundle_raises_the_named_error(text):
    with pytest.raises(pb.PortraitBundleError):
        pb.load_signed_recipes_from_bundle(text)


def test_og_coach_cards_reexports_the_one_reader():
    pytest.importorskip("PIL")
    from web import og_coach_cards as cc

    assert cc.load_signed_recipes_from_bundle is pb.load_signed_recipes_from_bundle


def test_sweep_names_the_warning_and_writes_nothing(capsys):
    pytest.importorskip("PIL")
    from web import og_coach_cards as cc

    class S3:
        def get_object(self, Bucket, Key):
            import io

            return {"Body": io.BytesIO(b'export const PORTRAITS = {"a":"x;y')}

        def put_object(self, **kw):  # pragma: no cover
            raise AssertionError("must not write")

    assert cc.sweep_coach_cards(S3(), "b") == []
    assert "PORTRAIT_BUNDLE_UNREADABLE" in capsys.readouterr().out


# ── the QA leg: a parse failure reaches qa-smoke, not only a log line ────────────────────────


def _fresh(*pids, age_h=2):
    return {p: NOW - timedelta(hours=age_h) for p in pids}


def test_qa_fails_on_an_unparseable_bundle():
    level, msg = qcc.assess_coach_cards('export const PORTRAITS = {"a":"x;y', {}, NOW)
    assert level == "fail" and "cannot read the portrait bundle" in msg


def test_qa_ok_when_every_card_is_fresh():
    level, msg = qcc.assess_coach_cards(FIXTURE, _fresh("a_coach", "b_coach"), NOW)
    assert level == "ok" and "2 coach share cards" in msg


def test_qa_warns_on_missing_and_stale_cards_naming_the_persona():
    modified = {"a_coach": None, "b_coach": NOW - timedelta(hours=qcc.MAX_AGE_HOURS + 5)}
    level, msg = qcc.assess_coach_cards(FIXTURE, modified, NOW)
    assert level == "warn" and "no card for: a_coach" in msg and "b_coach (35h)" in msg


def test_qa_empty_registry_is_ok():
    assert qcc.assess_coach_cards(_bundle({}), {}, NOW)[0] == "ok"


def test_card_path_matches_the_writer():
    assert qcc.card_path("sarah_chen") == "/assets/images/og-coach-sarah-chen.png"


def test_check_wrapper_maps_levels_and_fail_softs_on_fetch_error(monkeypatch):
    def boom(*a, **k):
        raise OSError("edge blip")

    monkeypatch.setattr(qcc.urllib.request, "urlopen", boom)
    [chk] = qcc.check_coach_cards()
    assert chk.passed is None and "fail-soft" in chk.message


def test_check_is_wired_into_the_nightly_run_list():
    src = open(os.path.join(ROOT, "lambdas", "operational", "qa_smoke_lambda.py")).read()
    assert '("coach_cards", check_coach_cards)' in src
