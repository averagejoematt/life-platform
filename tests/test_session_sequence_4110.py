def served(day: str, rows: list[dict]) -> dict:
    e = session_sequence.next_session(day, rows)
    assert e is not None and e["source"] == "session_sequence", e
    return e


# ── 1. the sequence, pinned ──────────────────────────────────────────────────
# (index, week, session_in_week, role, block, deload) for the first 39 sessions, by hand.
EXPECTED = [
    (i, i // 3 + 1, i % 3 + 1, [H, M, HM][i % 3], 1 if i < 18 else (2 if i < 36 else 3), (i // 3 + 1) in (6, 12)) for i in range(39)
]


def test_the_first_13_program_weeks_are_pinned():
    got = [
        (p["sequence_index"], p["week"], p["session_in_week"], p["session_role"], p["block"], p["deload"])
        for p in session_sequence.preview(39)
    ]
    assert got == EXPECTED
    assert session_sequence.position(1)["position_label"] == "week 1 · session 2 of 3 · moderate"
    assert session_sequence.position(15)["position_label"] == "week 6 · session 1 of 3 · heavy · DELOAD"


def test_the_sequence_is_defined_once_in_program_structure():
    seq = program_structure.SESSION_SEQUENCE
    assert seq["block_start"] == "2026-09-24"
    assert seq["session_roles"] == [H, M, HM] and seq["sessions_per_week"] == 3 and seq["weeks_per_block"] == 6
    assert set(seq["session_roles"]) <= set(program_structure.SESSION_TEMPLATES)
    assert program_structure.summary()["session_sequence"] is seq
    # the weekday calendar is retired, not kept beside the sequence as a second answer
    for gone in ("BLOCK_CALENDAR", "block_calendar", "calendar_entry", "_session_dates"):
        assert not hasattr(program_structure, gone), gone


