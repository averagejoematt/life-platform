"""tests/test_session_sequence_4110.py — v0.3's sessions follow a SEQUENCE, not weekdays.

WHY THIS FILE EXISTS

#4064 bound each v0.3 session to a weekday (Thu 09-24 / Sat 09-26 / Mon 09-28, then
Mon/Wed/Fri). Owner, 2026-09-23: "more just focusing on planned sequence and not forgetting
next if I audible a change." Under the weekday calendar a walk on a lifting day silently
SKIPPED that session. These tests hold the replacement:

  1. THE SEQUENCE IS PINNED. heavy -> moderate -> heavy-moderate, 3 per program week, deload
     every 6th week, block of 6 — written out literally, not generated by the code under test.
  2. THE ISSUE'S FIXTURES. Heavy done Thu, walk Fri, walk Sat -> Sun serves MODERATE (not a
     weekday slot's session); two sessions skipped do not advance the week; an Engine day
     (cardio only, logged in Hevy) does not advance it; a warm-up-only log does not; two
     loaded logs on one day are one session; a session before the block start does not count.
  3. THE MUTATION CONTROL. A predicate under which a walk advances the position reds the
     fixture — so the fixture is proven to be able to fail.
  4. ONE WEEK. `plan_engine.program_week` (the `not_before_week` gate, #4098), the served
     session's `week`, and the week the load ramp is handed (#4090) are the same number.
  5. THE SURFACES. `constraint_block` names the position and the session that advanced it;
     the generator builds the sequence's session on a day the old calendar called a walk;
     an unread Hevy record is `sequence_unreadable` / week None — never a silent session 1.
"""

