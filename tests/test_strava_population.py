# 4. Mutation proof — the out-of-population arm is load-bearing
# ══════════════════════════════════════════════════════════════════════════


def test_removing_the_out_of_population_arm_changes_a_published_percentile(monkeypatch):
    """Delete the arm (every type in-population, every record measured) and re-run the
    exact pipeline that publishes 'top N% distance ever' on an activity's name. If the
    published percentile does not move, the arm guards nothing.

    This is the figure the issue is about: the denominator of every all-time percentile
    on the site, in the digests and in MCP search.
    """
    from ingestion import enrichment_lambda

    api_acts = [
        _api_activity(sport_type="Run", type="Run", name="Long Run", distance=16093.4, total_elevation_gain=100),
        _api_activity(sport_type="Run", type="Run", name="Flat Run", distance=8046.72, total_elevation_gain=0),
    ] + [
        _api_activity(sport_type="WeightTraining", type="WeightTraining", name="Lift", distance=0, total_elevation_gain=0) for _ in range(8)
    ]

    def _pipeline():
        stored = [_day([_normalize(a) for a in api_acts])]
        sorted_elev, sorted_dist = enrichment_lambda.build_percentile_lookup(stored)
        long_run = stored[0]["activities"][0]
        return len(sorted_dist), enrichment_lambda.percentile(sorted_dist, long_run["distance_miles"])

    denom_with_arm, pct_with_arm = _pipeline()

    # The mutation: strip the population decision so every type is in, and every record
    # counts as measured — i.e. exactly the "coerce 0 correctly" fix the issue warns against.
    monkeypatch.setattr(pop, "DISTANCE_POPULATION", frozenset(pop._DECISIONS) | {"WeightTraining"})
    monkeypatch.setattr(pop, "ELEVATION_POPULATION", frozenset(pop._DECISIONS) | {"WeightTraining"})
    monkeypatch.setattr(pop, "has_measurement_channel", lambda activity: True)

    denom_mutated, pct_mutated = _pipeline()

    assert denom_with_arm == 2, "only the two runs have a measured distance"
    assert denom_mutated == 10, "the mutation sweeps all eight gym sessions into the population"
    assert pct_with_arm == 50.0
    assert pct_mutated == 90.0
    assert pct_with_arm != pct_mutated, "the out-of-population arm must change a published figure"
    # And the published LABEL flips with it — "top 10% distance ever" appears only in the
    # mutated world, manufactured entirely out of gym sessions that never had a distance.
    assert enrichment_lambda.percentile_label(pct_with_arm, "distance") is None
    assert enrichment_lambda.percentile_label(pct_mutated, "distance") == "top 10% distance ever"


