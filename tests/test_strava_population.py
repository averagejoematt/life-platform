"""tests/test_strava_population.py — the Strava distance/elevation population rule (#2331, ADR-104).

`strava_lambda._normalize` used to write ``round(...) if activity.get("distance") else None``.
`0` is falsy, so a genuinely flat run was stored as *unmeasured*. The naive repair —
un-collapse every zero — is worse: it would enter 758 gym `Workout` sessions and 650
indoor-trainer records into the distance population as measured 0.0-mile efforts, and the
all-time "top N%" claims the platform publishes are percentiles over exactly that
population. So #2331 is a population-membership decision first and a coercion second.

What these tests pin:

  * **The ADR-104 distinction, spelled out.** measured-zero → `0.0`; absent-because-the-
    metric-was-not-measured → `None`. Both directions, with the reason for each.
  * **The decision covers what ingestion actually produces.** The type set is checked
    against `config/strava_activity_type_census.json` — machine-generated by
    `scripts/strava_type_census.py` from the live archive — so a sport Matthew takes up
    next month reds this file instead of silently defaulting.
  * **Consumers tolerate the 0.** Every reader of `distance_miles` /
    `total_elevation_gain_feet` is exercised on the 0 path: the percentile pools (which
    change), the enriched-name builder, the digest/vacation-fund sums (which do not).
  * **The out-of-population arm is not vacuous.** A mutation that deletes it changes a
    published figure — the all-time percentile a reader sees on an activity.
  * **The reconciliation script re-derives the same rule and writes Decimal.**
"""

