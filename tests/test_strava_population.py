def _day(activities):
    return {"activities": activities}


def test_percentile_pool_membership_matches_the_writer_rule():
    """The pool's `is not None` gate and the writer's population rule must be the SAME
    population, or the denominator of every published percentile is a different set from
    the one the rule defines."""
    from ingestion import enrichment_lambda

    api_acts = [
        _api_activity(sport_type="Run", type="Run", distance=8046.72, total_elevation_gain=0),  # measured flat run
        _api_activity(sport_type="Run", type="Run", distance=16093.4, total_elevation_gain=100),
        _api_activity(sport_type="WeightTraining", type="WeightTraining", distance=0, total_elevation_gain=0),
        _api_activity(sport_type="Walk", type="Walk", trainer=True, distance=0, total_elevation_gain=0),
    ]
    stored = [_day([_normalize(a) for a in api_acts])]
    elevations, distances = enrichment_lambda.build_percentile_lookup(stored)

    expected_dist = sum(1 for a in api_acts if pop.distance_miles(a, a.get("distance")) is not None)
    expected_elev = sum(1 for a in api_acts if pop.elevation_gain_feet(a, a.get("total_elevation_gain")) is not None)
    assert len(distances) == expected_dist == 2
    assert len(elevations) == expected_elev == 2
    # The measured zero IS in the pool, at the bottom of the distribution.
    assert elevations[0] == 0.0


def test_enriched_name_does_not_print_a_zero_stat():
    """A 0.0mi / 0ft suffix would be noise on every flat activity — the name builder's
    truthiness check is correct HERE (it is a display choice, not a data claim)."""
    from ingestion import enrichment_lambda

    act = _normalize(_api_activity(name="Flat Loop", sport_type="Run", type="Run", distance=8046.72, total_elevation_gain=0))
    name = enrichment_lambda.build_enriched_name(act, None, [], [], [], [])
    assert "0ft" not in name
    assert "Flat Loop" in name


def test_extensive_day_totals_are_unchanged_by_the_fix():
    """`total_distance_miles` / `total_elevation_gain_feet` are sums over the whole day, so
    an absent value and a measured 0 contribute identically. Named here so nobody reads
    the fix as moving a headline number that it does not move."""
    from ingestion.strava_lambda import transform

    acts = [
        _normalize(_api_activity(sport_type="Run", type="Run", distance=8046.72, total_elevation_gain=0)),
        _normalize(_api_activity(sport_type="WeightTraining", type="WeightTraining", distance=0, total_elevation_gain=0)),
    ]
    rec = transform({"activities": acts}, "2026-08-10")[0]
    assert rec["total_distance_miles"] == 5.0
    assert rec["total_elevation_gain_feet"] == 0.0


@pytest.mark.parametrize("zero_value", [0.0])
def test_digest_and_vacation_fund_readers_tolerate_a_zero(zero_value):
    """The `or 0` readers must neither crash nor change their sum when a null becomes a
    measured 0. Exercised against the real reader expressions."""
    from content import vacation_fund
    from emails import weekly_digest_extractors  # noqa: F401

    act_zero = {"sport_type": "Run", "distance_miles": zero_value, "total_elevation_gain_feet": zero_value}
    act_null = {"sport_type": "Run", "distance_miles": None, "total_elevation_gain_feet": None}
    # weekly digest's per-activity render expression
    for act in (act_zero, act_null):
        assert round(float(act.get("distance_miles") or 0), 1) == 0.0
        assert round(float(act.get("total_elevation_gain_feet") or 0)) == 0
    # vacation fund's float coercion
    assert vacation_fund._f(zero_value) == 0.0
    assert vacation_fund._f(None) == 0.0


def test_search_activities_names_the_population_it_ranks_against():
    """Acceptance criterion 3 of #2331: a 'top N% all-time' claim must say what the N% is
    OF. `all_time_total_acts` is the denominator; `population` is its definition."""
    from mcp import tools_data

    assert tools_data._population_label("distance_miles") == pop.DISTANCE_POPULATION_LABEL
    assert tools_data._population_label("total_elevation_gain_feet") == pop.ELEVATION_POPULATION_LABEL
    for label in (pop.DISTANCE_POPULATION_LABEL, pop.ELEVATION_POPULATION_LABEL):
        assert "not indoor-trainer or manually entered" in label


