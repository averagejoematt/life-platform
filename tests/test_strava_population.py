def test_measured_zero_on_an_outdoor_run_is_stored_as_zero_not_absent():
    """The bug in one line: a pancake-flat GPS run measured 0 ft of gain. That is a
    measurement, it belongs in the elevation distribution, and it used to vanish."""
    out = _normalize(_api_activity(distance=8046.72, total_elevation_gain=0))
    assert out["total_elevation_gain_feet"] == 0.0, "a measured zero must survive as zero"
    assert out["total_elevation_gain_feet"] is not None
    assert out["distance_miles"] == 5.0


def test_absent_because_not_reported_stays_absent():
    """Strava omitting the key entirely is absence — never coerce it to 0."""
    out = _normalize(_api_activity(name="Walk"))
    assert out["distance_miles"] is None
    assert out["total_elevation_gain_feet"] is None


def test_gym_session_zero_is_absence_not_a_measured_zero():
    """Distance is not a property of a bench-press session. Strava's 0.0 is schema
    filler; publishing it as a measured 0.0 miles would be a fabricated data point."""
    for sport in ("WeightTraining", "Workout", "Yoga", "HighIntensityIntervalTraining"):
        out = _normalize(_api_activity(sport_type=sport, type=sport, distance=0, total_elevation_gain=0))
        assert out["distance_miles"] is None, sport
        assert out["total_elevation_gain_feet"] is None, sport
        # The raw API value is still stored verbatim — absence is a statement about the
        # DERIVED figure, not a reason to drop what Strava sent.
        assert out["distance_meters"] == 0


def test_indoor_trainer_zero_is_absence_even_on_a_distance_bearing_type():
    """The archive's dominant case: 372 WHOOP-synced Walks and 159 Rides with
    trainer=True and distance 0. Matthew plainly covered ground; the distance was not
    measured. Storing 0 would fabricate a measurement, which is the same ADR-104 sin
    pointing the other way."""
    out = _normalize(_api_activity(sport_type="Walk", type="Walk", trainer=True, distance=0, total_elevation_gain=0))
    assert out["distance_miles"] is None
    assert out["total_elevation_gain_feet"] is None


def test_manually_entered_zero_is_absence():
    """A hand-logged activity's 0 is an unfilled field, not a measurement."""
    out = _normalize(_api_activity(sport_type="Walk", type="Walk", manual=True, distance=0, total_elevation_gain=0))
    assert out["distance_miles"] is None


def test_indoor_trainer_keeps_a_nonzero_measurement():
    """The channel gate only decides ZEROS. A treadmill run with a footpod reports real
    distance; that must survive untouched."""
    out = _normalize(_api_activity(sport_type="Run", type="Run", trainer=True, distance=5000, total_elevation_gain=0))
    assert out["distance_miles"] == 3.11
    assert out["total_elevation_gain_feet"] is None  # 0 with no elevation channel → absent


def test_water_sports_are_in_distance_but_out_of_elevation_population():
    """A swim has a real distance and no meaningful vertical gain."""
    out = _normalize(_api_activity(sport_type="Swim", type="Swim", distance=0, total_elevation_gain=0))
    assert out["distance_miles"] == 0.0
    assert out["total_elevation_gain_feet"] is None


def test_unknown_activity_type_defaults_to_absent():
    """An unclassified sport must not silently join a published population."""
    out = _normalize(_api_activity(sport_type="Hovercraft", type="Hovercraft", distance=0, total_elevation_gain=0))
    assert out["distance_miles"] is None
    assert out["total_elevation_gain_feet"] is None


