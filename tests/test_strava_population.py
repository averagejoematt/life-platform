def test_reconciliation_plans_only_rows_the_rule_disagrees_with():
    import reconcile_strava_measured_zero as rec

    flat_run = {
        "sport_type": "Run",
        "distance_meters": 8046.72,
        "total_elevation_gain_meters": 0,
        "distance_miles": 5.0,
        "total_elevation_gain_feet": None,
    }
    gym = {
        "sport_type": "WeightTraining",
        "distance_meters": 0,
        "total_elevation_gain_meters": 0,
        "distance_miles": None,
        "total_elevation_gain_feet": None,
    }
    already_right = {
        "sport_type": "Run",
        "distance_meters": 8046.72,
        "total_elevation_gain_meters": 0,
        "distance_miles": 5.0,
        "total_elevation_gain_feet": 0.0,
    }

    assert rec.plan_activity(flat_run) == {"total_elevation_gain_feet": (None, 0.0)}
    assert rec.plan_activity(gym) == {}, "an already-correct absence is not a write"
    assert rec.plan_activity(already_right) == {}, "idempotent — a second run is a no-op"


def test_reconciliation_writes_decimal_never_float():
    """boto3 rejects float. #2331's writes are derived numbers, so this is the whole risk."""
    from decimal import Decimal

    import reconcile_strava_measured_zero as rec

    acts = [
        {
            "sport_type": "Run",
            "distance_meters": 8046.72,
            "total_elevation_gain_meters": 0,
            "distance_miles": 5.0,
            "total_elevation_gain_feet": None,
        }
    ]
    planned = rec.plan_day({"activities": acts})
    updated = rec._apply_changes(acts, planned)
    value = updated[0]["total_elevation_gain_feet"]
    assert isinstance(value, Decimal) and not isinstance(value, float)
    assert value == Decimal("0.0")
    assert acts[0]["total_elevation_gain_feet"] is None, "the input row must not be mutated in place"


def test_reconciliation_is_dry_run_unless_apply_is_passed():
    """Reading the source, not the behaviour: --apply must be an explicit opt-in flag, and
    every DDB write must sit behind it."""
    import ast
    import inspect

    import reconcile_strava_measured_zero as rec

    tree = ast.parse(inspect.getsource(rec.main))
    apply_flags = [n for n in ast.walk(tree) if isinstance(n, ast.Constant) and n.value == "--apply"]
    assert apply_flags, "the script must expose an explicit --apply flag"
    writes = [
        n for n in ast.walk(tree) if isinstance(n, ast.Attribute) and n.attr in ("update_item", "put_item", "delete_item", "batch_writer")
    ]
    assert writes, "sanity: the script does write when applied"
    # Every write is inside the `if args.apply:` block.
    apply_guards = [
        n
        for n in ast.walk(tree)
        if isinstance(n, ast.If)
        and isinstance(n.test, ast.Attribute)
        and n.test.attr == "apply"
        and isinstance(n.test.value, ast.Name)
        and n.test.value.id == "args"
    ]
    guarded = {
        id(w)
        for g in apply_guards
        for w in ast.walk(g)
        if isinstance(w, ast.Attribute) and w.attr in ("update_item", "put_item", "delete_item", "batch_writer")
    }
    assert {id(w) for w in writes} <= guarded, "a DDB write escapes the --apply guard"
