def _census():
    with open(CENSUS_PATH) as fh:
        return json.load(fh)


def test_every_observed_activity_type_carries_an_explicit_decision():
    """Acceptance criterion 1 of #2331: the rule's type set is derived from the archive,
    not hand-typed. Regenerate with `python3 scripts/strava_type_census.py --write`; a new
    type reds this test until its distance/elevation membership is decided deliberately."""
    census = _census()
    undecided = sorted(t for t in census["types"] if not pop.is_decided(t))
    assert undecided == [], f"activity types seen in the archive with no population decision: {undecided}"


def test_census_carries_its_provenance():
    """A census with no provenance is indistinguishable from a hand-typed list."""
    prov = _census()["_provenance"]
    assert prov["generated_by"] == "scripts/strava_type_census.py"
    assert prov["activities"] > 0 and prov["day_records"] > 0
    assert "read-only" in prov["source"]


def test_the_two_populations_are_not_the_same_set():
    """If they were, the per-metric decision would be decoration."""
    assert pop.DISTANCE_POPULATION != pop.ELEVATION_POPULATION
    assert "Swim" in pop.DISTANCE_POPULATION and "Swim" not in pop.ELEVATION_POPULATION
    assert "WeightTraining" not in pop.DISTANCE_POPULATION


