"""emails/nutrition_review_compact.py — the Saturday Nutrition Review as a three-minute read (#6245).

THE RULING (owner, 2026-11-23, outbound priority 1): shorten the Saturday Nutrition Review to about three minutes; keep
the practical menu and the shopping list; reduce repeated coach commentary, historical explanation and redundant
metrics; keep the detailed analysis on demand.

WHAT THE COMPACT EMAIL HOLDS, in order:
  1. one line on the week's logged intake, over COMPLETE days only, with the count and the dates — the seven-day table
     is not printed (a partly imported or not-yet-arrived day is named, never averaged);
  2. the coming week's calorie titration card, as the long format prints it (code-built, one decision);
  3. the code-built menu ahead and the shop: every day, every feeding, every serving and every grocery line the long
     format prints. What is dropped is repetition and machinery — the fixed dinner's sentence is stated once instead
     of on every day, a serving of one is not written "1 x", and the feeding hour offsets, fat and carbohydrate
     figures and the builder's own provenance note move to the session tool (`get_exercise_notes`
     action='weekly_menu'), which returns the full menu;
  4. the panel's priorities, ONE voice (the panel's unified "priorities" section, never an expert card), capped at
     ``PANEL_WORD_CAP`` words;
  5. one line naming where the rest is on request.

WHAT MOVES TO ON-DEMAND (no new page, no new store): the day-by-day table, micronutrients, meal timing (`get_nutrition`
with the week's dates), the menu's full figures (`get_exercise_notes` action='weekly_menu'), and the three expert
cards, meal ideas and supplement check — still generated by the same one model call, printed by the long format.

THE SWITCH (one DynamoDB item — the Morning Brief's own pattern, `emails.brief_trial.read_switch`; no new IAM: the
review's role already has GetItem on the table)::

    USER#matthew#SOURCE#outbound_format / SWITCH#nutrition_review   {"value": "compact" | "long"}

Only the exact word ``compact`` (trimmed, any case) selects this format. Absent, unreadable or anything else is the
long format, as today. Rollback is that one item set back to ``long`` (or deleted). No deploy either way.

PURE apart from ``read_format`` (one GetItem): no clock, no model, no write.
"""

from __future__ import annotations

import html as _html
import json
import re
from html.parser import HTMLParser
from typing import Any, Mapping, Optional

from common import food_log_state

FORMAT_LONG = "long"
FORMAT_COMPACT = "compact"
SWITCH_SOURCE = "outbound_format"
SWITCH_SK = "SWITCH#nutrition_review"

# ── the budget (owner ruling: about three minutes) ───────────────────────────────────────────────────────────────
#: Silent-reading pace the outbound inventory measured every email at.
WORDS_PER_MINUTE = 230
#: The whole rendered email: ~3 minutes at 230 wpm.
WORD_BUDGET = 700
#: Everything except the code-built menu and shop (the parts the owner kept): the week line, the titration card, the
#: panel's priorities, the on-demand line and the chrome. The menu's length follows the week's plan, so this is the
#: cap that holds whatever the plan is; a measured overrun of WORD_BUDGET is logged, never trimmed out of the menu.
PROSE_WORD_CAP = 330
#: The panel's prose: one voice.
PANEL_WORD_CAP = 150

# The panel's unified section heading (both prompt paths order "### Top 3 Nutrition Priorities This Week").
_PRIORITY_HEAD = re.compile(r"\bpriorit", re.I)
# Any heading that starts the NEXT unified section (or an expert card) ends the excerpt.
_NEXT_HEAD = re.compile(r"grocery|shopping|meal ideas|supplement check|webb|patel|okafor|reyes", re.I)
_WORD = re.compile(r"\S*[A-Za-z0-9]\S*")

ACCENT = "#4cc9f0"
_CARD = "background:#16213e;border-radius:8px;padding:14px 16px;margin-bottom:14px;font-size:14px;line-height:1.5;color:#e0e0e0;"
_HEAD = "font-size:12px;letter-spacing:1px;color:#9ca3af;font-weight:600;margin-bottom:6px;"


def read_format(table, user_prefix: str, logger=None) -> str:
    """The format switch. Only the exact word 'compact' selects the compact email; anything else, an absent item or a
    failed read is the long format (today's email)."""
    try:
        item = table.get_item(Key={"pk": f"{user_prefix}{SWITCH_SOURCE}", "sk": SWITCH_SK}).get("Item") or {}
    except Exception as e:  # noqa: BLE001 — fail to today's email
        if logger:
            logger.warning(f"nutrition review format switch read failed (long format): {type(e).__name__}")
        return FORMAT_LONG
    return FORMAT_COMPACT if str(item.get("value") or "").strip().lower() == FORMAT_COMPACT else FORMAT_LONG


# ── word counting ────────────────────────────────────────────────────────────────────────────────────────────────


def visible_text(html: str) -> str:
    """The text a reader sees: tags out, entities decoded."""
    text = re.sub(r"<(style|script)[^>]*>.*?</\1>", " ", html or "", flags=re.S | re.I)
    return _html.unescape(re.sub(r"<[^>]+>", " ", text))


def word_count(html: str) -> int:
    return len(_WORD.findall(visible_text(html)))


def read_minutes(words: int) -> float:
    return round(words / WORDS_PER_MINUTE, 1)


# ── the panel's one voice ────────────────────────────────────────────────────────────────────────────────────────


class _Blocks(HTMLParser):
    """Flattens the panel's HTML into text blocks, one per block element, each tagged as a heading or not."""

    _BLOCK = {"p", "div", "li", "h1", "h2", "h3", "h4", "h5", "h6", "tr", "br", "ul", "ol", "section", "table"}
    _HEADS = {"h1", "h2", "h3", "h4", "h5", "h6"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks: list[tuple[str, bool, bool]] = []  # (text, is_heading, is_list_item)
        self._buf: list[str] = []
        self._head = False
        self._li = False
        self._bold = False
        self._only_bold = True

    def _flush(self):
        text = re.sub(r"\s+", " ", "".join(self._buf)).strip()
        if text:
            self.blocks.append((text, self._head or (self._only_bold and len(text.split()) <= 8), self._li))
        self._buf, self._only_bold = [], True

    def handle_starttag(self, tag, attrs):
        if tag in self._BLOCK:
            self._flush()
            self._head, self._li = tag in self._HEADS, tag == "li"
        elif tag in ("strong", "b"):
            self._bold = True

    def handle_endtag(self, tag):
        if tag in self._BLOCK:
            self._flush()
            self._head = self._li = False
        elif tag in ("strong", "b"):
            self._bold = False

    def handle_data(self, data):
        if data.strip() and not self._bold:
            self._only_bold = False
        self._buf.append(data)


def _cap_words(text: str, cap: int) -> str:
    """`text` cut to at most `cap` words, at the last sentence end inside the cap when there is one."""
    words = text.split()
    if len(words) <= cap:
        return text
    cut = " ".join(words[:cap])
    end = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
    return cut[: end + 1] if end > len(cut) // 3 else cut + "…"  # the mark rides the last word: never a 151st


def panel_priorities(ai_html: str, cap: int = PANEL_WORD_CAP) -> list[str]:
    """The panel's unified priorities as plain-text items, at most `cap` words in all — the ONE voice the compact
    email prints. Empty when the section is not found (the email then says the priorities are in the long format)."""
    parser = _Blocks()
    try:
        parser.feed(ai_html or "")
        parser.close()
    except Exception:  # noqa: BLE001 — malformed model HTML: no excerpt rather than a broken email
        return []
    blocks = parser.blocks
    start = next((i for i, (t, head, _li) in enumerate(blocks) if head and _PRIORITY_HEAD.search(t)), None)
    if start is None:
        return []
    items: list[str] = []
    used = 0
    for text, head, _li in blocks[start + 1 :]:
        if head and _NEXT_HEAD.search(text):
            break
        if head and _PRIORITY_HEAD.search(text):
            continue
        room = cap - used
        if room <= 0:
            break
        piece = _cap_words(text, room)
        items.append(piece)
        used += len(piece.split())
    return items


# ── the menu, compact ────────────────────────────────────────────────────────────────────────────────────────────


def _esc(s: Any) -> str:
    return _html.escape(str(s), quote=False)


def _num(v: Any) -> str:
    try:
        return f"{float(v):g}"
    except (TypeError, ValueError):
        return "?"


def _items(items) -> str:
    """'2 x Tortilla, Flank steak' — a serving of one is not written '1 x'."""
    out = []
    for i in items or []:
        n = i.get("servings")
        out.append(i.get("label", "?") if _num(n) == "1" else f"{_num(n)} x {i.get('label', '?')}")
    return ", ".join(out)


def _fixed_note(fx: Mapping[str, Any], f: Mapping[str, Any]) -> str:
    fib = f"{_num(f.get('fibre_g'))} g fibre" if fx.get("fibre_known") else "fibre unknown"
    return (
        f"{fx.get('label', '?')} — fixed, planned at {_num(f.get('kcal'))} kcal, {_num(f.get('protein_g'))} g protein, {fib}; "
        "log its printed label"
    )


#: How a day line names its fixed feeding: left out (the note above the days says every day has the same one),
#: "the fixed dinner" (one fixed meal, not on every day), or by its label (more than one fixed meal).
FIXED_OMIT, FIXED_GENERIC, FIXED_LABEL = "omit", "generic", "label"


def _day_line(d: Mapping[str, Any], fixed_mode: str) -> str:
    tot = d.get("totals") or {}
    weekday = str(d.get("weekday") or "")[:3]
    date = str(d.get("date") or "")
    # the day type, and "cook" on a cook day (a meal-service day is the default and is not written)
    kind = ", ".join(str(x) for x in (d.get("day_type"), d.get("service")) if x and x != "meal_service")
    head = f"{weekday} {date[5:]}" + (f" ({kind})" if kind else "")
    if not d.get("feedings"):
        return f"{head}: not fitted ({'; '.join(d.get('misses') or [])})"
    verdict = "fits" if d.get("fits") else "does not fit: " + "; ".join(d.get("misses") or [])
    feeds = []
    for f in d["feedings"]:
        name = str(f.get("name") or "feeding").replace("feeding ", "")
        fx = f.get("fixed")
        if fx:
            if fixed_mode == FIXED_OMIT:
                continue
            name = re.sub(r"\s*\(fixed[^)]*\)", "", name)
            what = f"the fixed {f.get('slot') or 'meal'}" if fixed_mode == FIXED_GENERIC else f"{fx.get('label', '?')} (fixed)"
            extra = _items(f.get("items"))
            feeds.append(f"{name}: {what}" + (f" with {extra}" if extra else ""))
        else:
            feeds.append(f"{name}: {_items(f.get('items'))}")
    return f"{head} · {_num(tot.get('kcal'))} kcal, {_num(tot.get('protein_g'))} g protein — {verdict}. " + "; ".join(feeds)


# The quality line's priorities tail when it names nothing (weekly_menu: "... it names: none in the week").
_NOTHING_TAGGED = re.compile(r"\.\s*lab-driven priorities carried; [^.]*: none in the week\.?$")


def menu_section(ahead: Optional[Mapping[str, Any]], fd: Mapping[str, Any]) -> str:
    """The menu ahead and the shop, compact. Every day, feeding, serving and grocery line of the long format's block;
    the grocery and quality lines are the feed's own (``weekly_menu_feed.feed``), verbatim."""
    rows: list[str] = []
    fixed: dict[str, str] = {}
    days: list[Mapping[str, Any]] = []
    reasons: list[str] = []
    shop_weeks = [f"week of {w.get('week_start')} " for w in (ahead or {}).get("weeks") or [] if w.get("shop")]
    for w in (ahead or {}).get("weeks") or []:
        menu = w.get("menu") or {}
        if not menu.get("built"):
            reasons.append(f"week of {w.get('week_start')}: {menu.get('reason') or 'no reason recorded'}")
            continue
        for d in w.get("days") or []:
            days.append(d)
            for f in d.get("feedings") or []:
                if f.get("fixed"):
                    note = _fixed_note(f["fixed"], f)
                    fixed[note] = note
    fitted = [d for d in days if d.get("feedings")]
    every_day = (
        len(fixed) == 1
        and bool(fitted)
        and all(sum(1 for f in d["feedings"] if f.get("fixed") and not f.get("items")) == 1 for d in fitted)
        and all(sum(1 for f in d["feedings"] if f.get("fixed")) == 1 for d in fitted)
    )
    mode = FIXED_OMIT if every_day else FIXED_GENERIC if len(fixed) == 1 else FIXED_LABEL
    slot = next((f.get("slot") for d in fitted for f in d["feedings"] if f.get("fixed")), None) or "meal"
    if not fd.get("built") or not days and not fd.get("grocery"):
        reason = fd.get("reason") or "; ".join(reasons) or "no reason recorded"
        rows.append(f"<div>No code-built menu this week: {_esc(reason)}.</div>")
    else:
        if fixed:
            label = {FIXED_OMIT: f"Every day's {slot}", FIXED_GENERIC: f"The fixed {slot}, on the days that name it"}.get(
                mode, "Fixed meals"
            )
            rows.append(f"<div style='margin:0 0 8px;color:#9ca3af;'>{_esc(label)}: {_esc('; '.join(fixed))}.</div>")
        rows.extend(f"<div style='margin:0 0 6px;'>{_esc(_day_line(d, mode))}</div>" for d in days)
        if fd.get("grocery"):
            rows.append("<div style='margin:10px 0 4px;font-weight:600;color:#ffffff;'>The shop (coming week)</div>")
            rows.extend(f"<div style='margin:0 0 4px;'>{_esc(ln)}</div>" for ln in fd["grocery"])
        # the plan check for the week being shopped for (the current week's remaining days were shopped last week)
        quality = [_NOTHING_TAGGED.sub(".", ln) for ln in fd.get("quality") or [] if not shop_weeks or ln.startswith(tuple(shop_weeks))]
        rows.extend(f"<div style='margin:8px 0 0;color:#9ca3af;'>{_esc(ln)}</div>" for ln in quality)
        if reasons:
            rows.append(f"<div style='margin:8px 0 0;color:#9ca3af;'>Not built: {_esc('; '.join(reasons))}</div>")
    return f'<div style="{_CARD}border-left:3px solid {ACCENT};"><div style="{_HEAD}">THE MENU AHEAD</div>' + "".join(rows) + "</div>"


# ── the week line ────────────────────────────────────────────────────────────────────────────────────────────────


def _day_words(date: str) -> str:
    from datetime import datetime

    try:
        return datetime.strptime(date, "%Y-%m-%d").strftime("%a %b %-d")
    except (TypeError, ValueError):
        return str(date)


def week_line(
    days: list, summary: Mapping[str, Any], dates: Mapping[str, str], state_words: Mapping[str, str], last_arrival_day: Any = None
) -> str:
    """ONE sentence pair on the week's logged intake: the averages over complete days only, with how many and which
    dates; every incomplete day named by its log state (never as a missed meal). Replaces the seven-day table."""
    whole = sorted(d["date"] for d in days if d.get("completeness", "complete") == "complete")
    n = len(whole)
    if n == 0:
        lead = "No complete day of food data has arrived for this week yet, so no average is stated."
    else:
        span = _day_words(whole[0]) if n == 1 else f"{_day_words(whole[0])} – {_day_words(whole[-1])}"
        cal, pro = summary.get("avg_calories"), summary.get("avg_protein_g")
        figures = []
        if cal is not None:
            figures.append(f"{int(cal)} kcal")
        if pro is not None:
            figures.append(f"{int(pro)} g protein")
        what = " and ".join(figures) + " a day on average" if figures else "no calorie or protein totals"
        lead = f"Logged intake over {n} complete day{'s' if n != 1 else ''} ({span}): {what}."
    notes = []
    for d in sorted(days, key=lambda x: x.get("date") or ""):
        state = d.get("completeness", "complete")
        if state != "complete":
            notes.append(f"{_day_words(d['date'])} {state_words.get(state, 'incomplete')}")
    have = {d.get("date") for d in days}
    missing = [x for x in _window(dates) if x not in have]
    # a day with no row: its export has not arrived (data on its way), or it has and carries no log for the day
    pending = [x for x in missing if food_log_state.arrival(x, last_arrival_day) == food_log_state.NOT_ARRIVED]
    unlogged = [x for x in missing if x not in pending]
    tail = ""
    if notes:
        tail += " Not counted: " + "; ".join(notes) + "."
    if pending:
        tail += f" Not arrived yet: {', '.join(_day_words(x) for x in pending)}."
    if unlogged:
        tail += f" No food log for {', '.join(_day_words(x) for x in unlogged)}."
    return lead + tail


def _window(dates: Mapping[str, str]) -> list[str]:
    from common.pacific_time import shift_day_key

    out: list[str] = []
    d = dates.get("this_start")
    while d and dates.get("this_end") and d <= dates["this_end"] and len(out) < 8:
        out.append(d)
        d = shift_day_key(d, 1)
    return out


# ── the email ────────────────────────────────────────────────────────────────────────────────────────────────────


def on_demand_line(dates: Mapping[str, str]) -> str:
    return (
        f"On request: the daily table, micronutrients and meal timing (get_nutrition, {dates.get('this_start')} to "
        f"{dates.get('this_end')}); full menu figures (get_exercise_notes, weekly_menu); the panel's full notes (long format)."
    )


def build(
    *,
    week_text: str,
    titration_html: str,
    menu_html: str,
    priorities: list,
    panel_state: str,
    dates: Mapping[str, str],
) -> str:
    """The compact email. `panel_state`: 'ok' (priorities found), 'missing' (a real edition without the section),
    'unavailable' (the failure or no-food card stood in for the panel)."""
    try:
        from datetime import datetime

        s = datetime.strptime(dates["this_start"], "%Y-%m-%d")
        e = datetime.strptime(dates["this_end"], "%Y-%m-%d")
        label = f'{s.strftime("%b %-d")} – {e.strftime("%b %-d, %Y")}'
    except Exception:  # noqa: BLE001
        label = f"{dates.get('this_start')} – {dates.get('this_end')}"
    if priorities:
        body = "".join(f"<li style='margin:0 0 4px;'>{_esc(p)}</li>" for p in priorities)
        panel = f"<ul style='margin:0;padding-left:18px;'>{body}</ul>"
    elif panel_state == "unavailable":
        panel = "<div>The panel's note is not available this week; the menu and the shop above are complete.</div>"
    else:
        panel = "<div>The panel's priorities were not found in its note this week; its full note is the long format.</div>"
    return (
        '<div style="max-width:600px;margin:0 auto;background:#1a1a2e;font-family:-apple-system,BlinkMacSystemFont,'
        "'Segoe UI',sans-serif;padding:16px;color:#e0e0e0;\">"
        f'<div style="margin-bottom:14px;"><div style="font-size:18px;font-weight:700;color:#ffffff;">Nutrition Review</div>'
        f'<div style="color:#9ca3af;font-size:13px;">{_esc(label)}</div></div>'
        f'<div style="{_CARD}">{_esc(week_text)}</div>'
        f"{titration_html}{menu_html}"
        f'<div style="{_CARD}border-left:3px solid {ACCENT};"><div style="{_HEAD}">THIS WEEK\'S PRIORITIES</div>{panel}</div>'
        f'<div style="color:#9ca3af;font-size:12px;margin:4px 0 12px;">{_esc(on_demand_line(dates))}</div>'
        '<div style="color:#6b7280;font-size:10px;border-top:1px solid #2a2d4a;padding-top:10px;">'
        "Personal health tracking only &mdash; not medical advice.</div></div>"
    )


def render(data, days, summary, ai_content, titration_html, *, is_panel, state_words, last_arrival, logger) -> Optional[str]:
    """The whole compact email from the handler's own values, or None when it cannot be built — the handler then sends
    the long format (today's email) and the log says so. Logs ONE size line per build."""
    try:
        if is_panel:
            priorities = panel_priorities(ai_content)
            panel_state = "ok" if priorities else "missing"
        else:
            priorities, panel_state = [], "unavailable"
        menu_html = menu_section(data.get("menu_ahead"), data.get("menu_feed") or {})
        html = build(
            week_text=week_line(days, summary, data["dates"], state_words, last_arrival),
            titration_html=titration_html,
            menu_html=menu_html,
            priorities=priorities,
            panel_state=panel_state,
            dates=data["dates"],
        )
    except Exception as e:  # noqa: BLE001 — the review still ships, in the long format
        logger.error(f"[nutrition-review-format] compact build failed, sending the long format: {type(e).__name__}: {e}")
        return None
    size = measure(html, menu_html)
    logger.info(f"[nutrition-review-format] {json.dumps(dict(size, format='compact', panel=panel_state), sort_keys=True)}")
    return html


def measure(html: str, menu_html: str) -> dict:
    """The send's own size record (logged, one line): words, the menu's share, the estimated reading minutes."""
    words, menu_words = word_count(html), word_count(menu_html)
    return {
        "words": words,
        "menu_words": menu_words,
        "prose_words": words - menu_words,
        "read_minutes_est": read_minutes(words),
        "over_budget": words > WORD_BUDGET,
    }
