#!/usr/bin/env python3
"""Serve the maintained privacy policy at its own address on the v9 site (#5920).

Since the 1 November cut-over, ``/privacy/`` is the v9 summary page and the maintained full policy,
``site/privacy/index.html`` (the owner's first-person text plus the permanence clauses that
``scripts/v4_build_permanence_terms.py`` renders into it), is a REPLACED destination: it stays in the repo,
the site sync excludes it, and it is served nowhere. Moving it would break the replaced-set guards, so the
policy stays where it is and this script derives a TWIN of it for the v9 build:

* source — ``site/privacy/index.html``: still the one place the policy is edited (and the one the permanence
  generator and ``tests/test_permanence_public_page_2574.py`` pin).
* twin — ``www/src/privacy/policy.json``: the policy's body (the short version through section 10, the live
  archive panel's markup included) and its last-updated date in words. ``www/src/pages/privacy/policy/``
  renders it at ``/privacy/policy/``; ``islands/permanence.js`` fills the live panel.

Nobody hand-copies the policy: ``tests/test_privacy_policy_twin_5920.py`` asserts the committed twin is exactly
what this script produces from the source today, so an edit to the policy that is not regenerated reds CI, and
because the twin lives under ``www/`` its regeneration is what deploys the change.

Usage::

    python3 scripts/v9_privacy_policy_twin.py            # write the twin
    python3 scripts/v9_privacy_policy_twin.py --check    # verify, exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "site", "privacy", "index.html")
TWIN = os.path.join(ROOT, "www", "src", "privacy", "policy.json")

BODY_START = '<div class="policy-tldr">'
BODY_END = '<p class="policy-back">'
UPDATED = re.compile(r'<p class="policy-updated">\s*last updated\s*·\s*([^<]+?)\s*</p>', re.IGNORECASE)
MONTHS = (
    "january",
    "february",
    "march",
    "april",
    "may",
    "june",
    "july",
    "august",
    "september",
    "october",
    "november",
    "december",
)


def updated_in_words(source_text: str) -> str:
    """'last updated · 14 november 2026' → '14 November 2026' (the page states dates in words, never ISO)."""
    m = UPDATED.search(source_text)
    if not m:
        raise ValueError(f"{os.path.relpath(SOURCE, ROOT)} carries no 'last updated · …' line")
    words = m.group(1).split()
    if not words or not all(w.isdigit() or w.lower() in MONTHS for w in words):
        raise ValueError(f"the policy's last-updated line is not a date in words: {m.group(1)!r}")
    return " ".join(w.capitalize() if w.lower() in MONTHS else w for w in words)


def body(source_text: str) -> str:
    """The policy from its short version through section 10 — everything between the title block and the back link."""
    if BODY_START not in source_text or BODY_END not in source_text:
        raise ValueError(f"{os.path.relpath(SOURCE, ROOT)} lost its body markers ({BODY_START} … {BODY_END})")
    start = source_text.index(BODY_START)
    end = source_text.index(BODY_END)
    text = source_text[start:end].strip()
    if re.search(r"<script\b", text, re.IGNORECASE) or re.search(r"\son[a-z]+\s*=", text, re.IGNORECASE):
        raise ValueError("the policy body carries a script or an inline handler — the v9 CSP forbids both")
    return text


def build(source: str = SOURCE) -> str:
    with open(source, encoding="utf-8") as fh:
        text = fh.read()
    twin = {
        "_about": (
            "GENERATED by scripts/v9_privacy_policy_twin.py from site/privacy/index.html (#5920) — do not edit; "
            "edit the source and regenerate. Rendered at /privacy/policy/ by www/src/pages/privacy/policy/index.astro."
        ),
        "source": "site/privacy/index.html",
        "updated": updated_in_words(text),
        "body": body(text),
    }
    return json.dumps(twin, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify the twin matches the policy; exit 1 on drift")
    args = ap.parse_args()

    wanted = build()
    current = None
    if os.path.exists(TWIN):
        with open(TWIN, encoding="utf-8") as fh:
            current = fh.read()
    rel = os.path.relpath(TWIN, ROOT)
    if current == wanted:
        print(f"privacy policy twin: {rel} matches site/privacy/index.html")
        return 0
    if args.check:
        print(f"DRIFT: {rel} no longer matches site/privacy/index.html", file=sys.stderr)
        print("       run: python3 scripts/v9_privacy_policy_twin.py", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(TWIN), exist_ok=True)
    with open(TWIN, "w", encoding="utf-8") as fh:
        fh.write(wanted)
    print(f"privacy policy twin: wrote {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
