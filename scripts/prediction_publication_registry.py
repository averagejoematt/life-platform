#!/usr/bin/env python3
"""scripts/prediction_publication_registry.py — the reviewed registry of publication-eligible legacy calls (owner ruling
2026-11-05; policy: ``lambdas/common/prediction_publication.py``).

Two commands, neither of which writes to AWS:

  emit --reviewed <file>   Regenerate ``lambdas/common/prediction_publication_registry.py`` from a reviewer's
                           classification file. The file lives OUTSIDE the repository (it names private calls);
                           its shape: ``{"through": {"call": iso, "ask": iso, "docket": iso},
                           "public": [[pk, key], ...]}`` where ``key`` is a call's ``prediction_id`` (an ask's or a
                           bet's sort key). Only the PUBLIC identities are written, as digests; the private ones are
                           never named, so the module carries no private id, wording or count.

  audit [--show-private]   Read every governed partition (read-only Query) and print how the policy classifies it:
                           counts per kind, class and reason. ``--show-private`` also prints each private row's
                           key and words to THIS terminal, for the owner's review — never redirect it into the repo.

The registry is frozen at its ``THROUGH`` instants: a call filed after them is classified by its own structure, by the
same pure function every public read applies (``prediction_publication.row_is_public``).
"""

from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lambdas"))

TARGET = ROOT / "lambdas" / "common" / "prediction_publication_registry.py"
PER_LINE = 7

HEADER = '''"""GENERATED by scripts/prediction_publication_registry.py (emit) — do not edit by hand.

The reviewed classification registry of the owner ruling of 2026-11-05 (``common.prediction_publication``): the
digest of every call, ask and bet filed on or before ``THROUGH`` that the review found PUBLICATION-ELIGIBLE. A reviewed
call that is not eligible is absent — this module names no private call, carries none of its words and does not say
how many there are. Every digest is a public row's, so its size says nothing the public routes do not.

A digest is ``prediction_publication.digest(pk, key)``: the first 16 hex characters of a SHA-256 over the partition
key and the call's ``prediction_id`` (an ask's or a bet's sort key).
"""

'''


def _packed(digests: list) -> str:
    lines = []
    for i in range(0, len(digests), PER_LINE):
        lines.append('    "' + " ".join(digests[i : i + PER_LINE]) + '",')
    return "\n".join(lines)


def render(through: dict, digests: list) -> str:
    body = HEADER
    body += "THROUGH = {\n" + "".join(f'    "{k}": "{through[k]}",\n' for k in sorted(through)) + "}\n\n"
    body += "_PACKED = (\n" + _packed(sorted(set(digests))) + "\n)\n\n"
    body += "PUBLIC_DIGESTS = frozenset(d for line in _PACKED for d in line.split())\n"
    return body


def cmd_emit(path: str) -> int:
    from common import prediction_publication as PP

    reviewed = json.loads(Path(path).read_text())
    through = {k: str(v) for k, v in reviewed["through"].items()}
    digests = [PP.digest(pk, key) for pk, key in reviewed["public"]]
    TARGET.write_text(render(through, digests))
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(set(digests))} public identities")
    return 0


def _partitions():
    from coach.persona_registry import short_id_names
    from common import prediction_publication as PP

    pks = [f"COACH#{c}_coach" for c in short_id_names(include_retired=True)]
    return pks + [PP.DOCKET_PK, "USER#matthew#SOURCE#calibration"]


def cmd_audit(show_private: bool) -> int:
    import boto3
    from boto3.dynamodb.conditions import Key
    from common import prediction_publication as PP

    table = boto3.resource("dynamodb", region_name="us-west-2").Table("life-platform")

    def lookup(pk, key):
        return table.get_item(Key={"pk": pk, "sk": PP.CALL_ROW_PREFIX + key}).get("Item")  # a read

    tally: collections.Counter = collections.Counter()
    for pk in _partitions():
        kw = {"KeyConditionExpression": Key("pk").eq(pk)}
        while True:
            resp = table.query(**kw)
            for row in resp.get("Items", []):
                kind = PP.kind_of(pk, row.get("sk"))
                if kind is None:
                    continue
                cls, reason = PP.classify(pk, row, lookup)
                tally[(kind, cls, reason)] += 1
                if show_private and cls == PP.PRIVATE:
                    words = row.get("claim_natural") or row.get("commitment_natural") or row.get("topic") or ""
                    print(f"PRIVATE {kind:9} {reason:22} {pk} {row.get('sk')} | {str(words)[:120]}")
            if not resp.get("LastEvaluatedKey"):
                break
            kw["ExclusiveStartKey"] = resp["LastEvaluatedKey"]
    for (kind, cls, reason), n in sorted(tally.items()):
        print(f"{kind:9} {cls:8} {reason:22} {n}")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("emit")
    e.add_argument("--reviewed", required=True)
    a = sub.add_parser("audit")
    a.add_argument("--show-private", action="store_true")
    args = ap.parse_args(argv)
    if args.cmd == "emit":
        return cmd_emit(args.reviewed)
    return cmd_audit(args.show_private)


if __name__ == "__main__":
    raise SystemExit(main())
