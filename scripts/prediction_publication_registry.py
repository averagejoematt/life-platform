#!/usr/bin/env python3
"""scripts/prediction_publication_registry.py — the reviewed registry of publication-eligible legacy calls (owner ruling
2026-11-05; policy: ``lambdas/common/prediction_publication.py``).

Four commands, none of which writes to AWS:

  emit --reviewed <file>   Regenerate ``lambdas/common/prediction_publication_registry.py`` from a reviewer's
                           classification file. The file lives OUTSIDE the repository (it names private calls);
                           its shape: ``{"through": {"call": iso, "ask": iso, "docket": iso},
                           "public": [[pk, key], ...]}`` where ``key`` is a call's ``prediction_id`` (an ask's or a
                           bet's sort key). Only the PUBLIC identities are written, as digests; the private ones are
                           never named, so the module carries no private id, wording or count.

  audit [--show-private]   Read every governed partition (read-only Query) and print how the policy classifies it:
                           counts per kind, class and reason. ``--show-private`` also prints each private row's
                           key and words to THIS terminal, for the owner's review — never redirect it into the repo.

  review [--out <file>]    REVIEW-ONLY (owner ruling 2026-11-06: "make it review-only. It may generate a proposed
                           publication manifest; it must not automatically approve or publish sensitive free text").
                           Reads the governed partitions (read-only Query) and writes a PROPOSED manifest of every
                           call, ask or bet waiting for review (a free-text observation, an unresolvable metric, a
                           bet filed after the registry) to a PRIVATE file outside the repository (default
                           ``~/.life-platform/private/call_review/proposed-<date>.json``, mode 0600; a path inside
                           the checkout is refused). Every entry is written ``"approve": false``. It never edits the
                           registry, never writes the table, and prints no count. It rides the weekly review clock
                           (``scripts/operating_calendar.py`` ``fullreview-delta``), not a schedule of its own.

  approve --manifest <file> The owner's act, after reading the proposal: every entry he set ``"approve": true`` is added
                           to the registry module (a repo edit that lands by code review, like any other). An entry the
                           rules hold private (journal or self-report words, a private metric, a legacy row the review
                           already decided) cannot be approved — the command refuses and writes nothing.

The registry is frozen at its ``THROUGH`` instants: a call filed after them is classified by its own structure, by the
same pure function every public read applies (``prediction_publication.row_is_public``), unless the owner approved it.
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lambdas"))

TARGET = ROOT / "lambdas" / "common" / "prediction_publication_registry.py"
PER_LINE = 7

HEADER = '''"""GENERATED by scripts/prediction_publication_registry.py (emit / approve) — do not edit by hand.

The reviewed classification registry of the owner ruling of 2026-11-05 (``common.prediction_publication``): the
digest of every call, ask and bet filed on or before ``THROUGH`` that the review found PUBLICATION-ELIGIBLE, plus any
later one the owner approved (``approve``, owner ruling 2026-11-06). A reviewed
call that is not eligible is absent — this module names no private call, carries none of its words and does not say
how many there are. Every digest is a public row's, so its size says nothing the public routes do not.

A digest is ``prediction_publication.digest(pk, key)``: the first 16 hex characters of a SHA-256 over the partition
key and the call's ``prediction_id`` (an ask's or a bet's sort key).
"""

'''


def _packed(digests: list) -> str:
    lines = []
    for i in range(0, len(digests), PER_LINE):
        lines.append('    "' + " ".join(digests[i : i + PER_LINE]) + '",')
    return "\n".join(lines)


def render(through: dict, digests: list) -> str:
    body = HEADER
    body += "THROUGH = {\n" + "".join(f'    "{k}": "{through[k]}",\n' for k in sorted(through)) + "}\n\n"
    body += "_PACKED = (\n" + _packed(sorted(set(digests))) + "\n)\n\n"
    body += "PUBLIC_DIGESTS = frozenset(d for line in _PACKED for d in line.split())\n"
    return body


def cmd_emit(path: str) -> int:
    from common import prediction_publication as PP

    reviewed = json.loads(Path(path).read_text())
    through = {k: str(v) for k, v in reviewed["through"].items()}
    digests = [PP.digest(pk, key) for pk, key in reviewed["public"]]
    TARGET.write_text(render(through, digests))
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(set(digests))} public identities")
    return 0


def _partitions():
    from coach.persona_registry import short_id_names
    from common import prediction_publication as PP

    pks = [f"COACH#{c}_coach" for c in short_id_names(include_retired=True)]
    return pks + [PP.DOCKET_PK, "USER#matthew#SOURCE#calibration"]


def cmd_audit(show_private: bool) -> int:
    import boto3
    from boto3.dynamodb.conditions import Key
    from common import prediction_publication as PP

    table = boto3.resource("dynamodb", region_name="us-west-2").Table("life-platform")

    def lookup(pk, key):
        return table.get_item(Key={"pk": pk, "sk": PP.CALL_ROW_PREFIX + key}).get("Item")  # a read

    tally: collections.Counter = collections.Counter()
    for pk in _partitions():
        kw = {"KeyConditionExpression": Key("pk").eq(pk)}
        while True:
            resp = table.query(**kw)
            for row in resp.get("Items", []):
                kind = PP.kind_of(pk, row.get("sk"))
                if kind is None:
                    continue
                cls, reason = PP.classify(pk, row, lookup)
                tally[(kind, cls, reason)] += 1
                if show_private and cls == PP.PRIVATE:
                    words = row.get("claim_natural") or row.get("commitment_natural") or row.get("topic") or ""
                    print(f"PRIVATE {kind:9} {reason:22} {pk} {row.get('sk')} | {str(words)[:120]}")
            if not resp.get("LastEvaluatedKey"):
                break
            kw["ExclusiveStartKey"] = resp["LastEvaluatedKey"]
    for (kind, cls, reason), n in sorted(tally.items()):
        print(f"{kind:9} {cls:8} {reason:22} {n}")
    return 0


# ── review-only: the proposed publication manifest (owner ruling 2026-11-06) ─────────────────────────
#: What a review may PROPOSE for approval: the reasons the rules leave to the owner. Everything else private is decided
#: by a rule (journal or self-report words, a private metric) or by the legacy review, and is never approvable.
REVIEWABLE = frozenset({"unclassified_subject", "unclassified_metric", "unreviewed_bet"})
DEFAULT_REVIEW_DIR = Path.home() / ".life-platform" / "private" / "call_review"


def _review_key(pk, row):
    """``(kind, identity key)`` of a row a review can propose, or None (a row that names a call follows that call)."""
    from common import prediction_publication as PP

    kind = PP.kind_of(pk, row.get("sk"))
    if kind == PP.CALL:
        return kind, PP.call_key(row.get("sk"), row)
    if kind in (PP.ASK, PP.DOCKET):
        return kind, row.get("sk")
    if kind == PP.REFERENCE and not row.get("prediction_id") and row.get("docket_ref"):
        return kind, row.get("sk")  # a docket learning: part of its bet, reviewed as itself
    return None


def pending(rows_by_pk: dict, lookup=None) -> list:
    """Pure: the rows waiting for the owner's review, as proposal entries. Never approves anything."""
    from common import prediction_publication as PP

    out = []
    for pk, rows in rows_by_pk.items():
        for row in rows:
            ident = _review_key(pk, row)
            if ident is None:
                continue
            cls, reason = PP.classify(pk, row, lookup)
            if cls != PP.PRIVATE or reason not in REVIEWABLE:
                continue
            words = " / ".join(str(row.get(k)) for k in ("claim_natural", "commitment_natural", "claim", "topic") if row.get(k))
            out.append(
                {
                    "pk": pk,
                    "key": ident[1],
                    "kind": ident[0],
                    "reason": reason,
                    "filed_at": row.get("created_at") or row.get("opened_at"),
                    "words": words[:600],
                    "approve": False,  # the review proposes; only the owner sets this
                }
            )
    out.sort(key=lambda e: (str(e["filed_at"] or ""), e["pk"], str(e["key"])))
    return out


def _inside_repo(path: Path) -> bool:
    p, root = path.expanduser().resolve(), ROOT.resolve()
    return p == root or root in p.parents


def write_proposal(entries: list, out: Path) -> Path:
    """The proposal, written privately (0600) outside the checkout. Raises on a path inside the repository."""
    out = out.expanduser()
    if _inside_repo(out):
        raise ValueError(f"refusing to write a proposal inside the repository: {out}")
    out.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(str(out), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        json.dump(
            {"generated_on": date.today().isoformat(), "status": "proposed — nothing here is approved", "entries": entries}, fh, indent=1
        )
    return out


def read_rows(table) -> dict:
    """Every governed partition, read (Query only)."""
    from boto3.dynamodb.conditions import Key

    out = {}
    for pk in _partitions():
        rows, kw = [], {"KeyConditionExpression": Key("pk").eq(pk)}
        while True:
            resp = table.query(**kw)
            rows.extend(resp.get("Items", []))
            if not resp.get("LastEvaluatedKey"):
                break
            kw["ExclusiveStartKey"] = resp["LastEvaluatedKey"]
        out[pk] = rows
    return out


def cmd_review(out, table=None) -> int:
    from common import prediction_publication as PP

    if table is None:
        import boto3

        table = boto3.resource("dynamodb", region_name="us-west-2").Table("life-platform")
    target = Path(out) if out else DEFAULT_REVIEW_DIR / f"proposed-{date.today().isoformat()}.json"
    if _inside_repo(target):
        print(f"refusing: {target} is inside the repository — a proposal names private calls", file=sys.stderr)
        return 2

    def lookup(pk, key):
        return table.get_item(Key={"pk": pk, "sk": PP.CALL_ROW_PREFIX + key}).get("Item")  # a read

    path = write_proposal(pending(read_rows(table), lookup), target)
    print(f"proposed manifest written (private, review-only): {path}")
    return 0


def approve(manifest: dict) -> list:
    """Pure: the digests the owner approved, or ValueError when an approved entry is not approvable."""
    from common import prediction_publication as PP

    out = []
    for e in manifest.get("entries") or []:
        if e.get("approve") is not True:
            continue
        if e.get("reason") not in REVIEWABLE:
            raise ValueError(f"not approvable ({e.get('reason')}): {e.get('pk')} {e.get('key')}")
        out.append(PP.digest(e["pk"], e["key"]))
    return out


def cmd_approve(path: str, target: Path = TARGET) -> int:
    from common import prediction_publication_registry as REG

    try:
        added = approve(json.loads(Path(path).expanduser().read_text()))
    except ValueError as e:
        print(f"refused, nothing written: {e}", file=sys.stderr)
        return 2
    if not added:
        print("nothing approved — the registry is unchanged")
        return 0
    target.write_text(render(dict(REG.THROUGH), sorted(set(REG.PUBLIC_DIGESTS) | set(added))))
    print(f"approved into {target.name}; commit it through a PR")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("emit")
    e.add_argument("--reviewed", required=True)
    a = sub.add_parser("audit")
    a.add_argument("--show-private", action="store_true")
    r = sub.add_parser("review")
    r.add_argument("--out")
    p = sub.add_parser("approve")
    p.add_argument("--manifest", required=True)
    args = ap.parse_args(argv)
    if args.cmd == "emit":
        return cmd_emit(args.reviewed)
    if args.cmd == "review":
        return cmd_review(args.out)
    if args.cmd == "approve":
        return cmd_approve(args.manifest)
    return cmd_audit(args.show_private)


if __name__ == "__main__":
    raise SystemExit(main())
