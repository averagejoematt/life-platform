#!/usr/bin/env python3
"""
coach_sim_scenarios.py — the conversation corpus for ``coach_chat_sim.py``.

TWO KINDS OF SCENARIO, AND THE SPLIT IS THE POINT.

**Core archetypes** run against every coach. They are domain-free on purpose: they
probe the properties the humanity roadmap claims are universal — register symmetry,
person-before-service-line, honest absence, repair after a correction, holding an
opinion. Running the identical scenario across eight personas is what turns "this
reply felt robotic" into "archetype X fails on 6 of 8 coaches, so it's an engine
defect, not a voice-spec defect." A per-coach-only corpus can never make that
distinction, and the distinction is what decides whether the fix goes in the prompt
rules or in one config/coaches/*.json.

**Domain scenarios** are what Matthew would actually text THIS coach about. They test
the other half: whether the persona knows its lane, cites its own numbers correctly,
and refuses honestly when the data isn't there.

WHY THE TURN COUNTS VARY. Real texting is not a fixed-depth tree. A "hey" exchange is
two turns and the humanity failure is over-replying; a decision conversation is six
and the failure is question-compulsion or a collapse into bullet-point advice. A flat
6-turn corpus would over-sample the middle and miss both tails — and would cost 40%
more for less signal.

THE OPENER RULE. An archetype whose failure mode depends on the EXACT inbound text
pins its opener verbatim ("hey" must be lowercase and three characters, or the
register-symmetry measurement is testing something else). Everything after turn 0 is
generated by the Matthew simulator so the conversation can actually go somewhere.

PRIVACY. This file is committed to a public repository. Scenarios stay on topics the
site already publishes — sleep, training, nutrition, labs, mood — and carry no
private detail. The real transcripts that calibrated the register are read at runtime
from DynamoDB and never land here.
"""

