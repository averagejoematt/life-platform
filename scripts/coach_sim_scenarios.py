# A conversational label for the simulator's prompt — "your sleep coach" reads
# naturally where "sleep_coach" would leak the id into Matthew's own voice.
LABELS = {
    "sleep_coach": "sleep coach",
    "nutrition_coach": "nutrition coach",
    "mind_coach": "mind coach",
    "physical_coach": "training coach",
    "explorer_coach": "longevity coach",
    "pattern_coach": "pattern analyst",
    "career_coach": "career coach",
    "eli_marsh": "program lead",
}


def build_corpus(coaches: list) -> list:
    """Every (coach x scenario) pair, core archetypes first.

    Core-first ordering is deliberate: if the spend cap halts the run early, what
    survives is the cross-coach comparable set — the half that can distinguish an
    engine defect from a voice-spec defect. A halted run that kept only domain
    scenarios would be the less useful half.
    """
    corpus = []
    for coach in coaches:
        label = LABELS.get(coach, "coach")
        for c in CORE:
            corpus.append(
                {
                    "id": f"{coach}::{c['archetype']}",
                    "coach": coach,
                    "coach_label": label,
                    "archetype": c["archetype"],
                    "opener": c["opener"],
                    "turns": c["turns"],
                    "stance": c["stance"],
                }
            )
    for coach in coaches:
        label = LABELS.get(coach, "coach")
        for name, opener, turns in DOMAIN.get(coach, []):
            corpus.append(
                {
                    "id": f"{coach}::domain_{name}",
                    "coach": coach,
                    "coach_label": label,
                    "archetype": f"domain_{name}",
                    "opener": opener,
                    "turns": turns,
                    "stance": (
                        "You opened with a real question in this coach's lane. Follow up naturally — "
                        "push for specifics if the answer is vague, drop it if you're satisfied."
                    ),
                }
            )
    return corpus
